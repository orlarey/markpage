#!/usr/bin/env node
/************************** vendor-ebnf2railroad.mjs ***************************
 *
 * Purpose: Regenerate packages/markpage-render/src/vendor/ebnf2railroad.ts,
 *   the copy of `ebnf2railroad` the ```ebnf fence renders with.
 *
 *   markpage uses three functions of that package: the EBNF parser, the
 *   per-production diagram builder and the table-of-contents helpers the
 *   builder takes its metadata from. The package itself also carries a
 *   command line and HTML / Markdown report builders, and through them
 *   depends on `showdown` — unmaintained, with open advisories in every
 *   version (ReDoS, XSS) — plus `prettier` and `commander`. As a dependency
 *   it put all of that in every install, and `npm audit` could only offer to
 *   downgrade it to 1.0.0. Vendored, only the code that runs is in the tree.
 *
 * How: Install the pinned version in a temporary folder, bundle the three
 *   entry points with esbuild into one ES module — `@prantlf/railroad-diagrams`
 *   (the SVG drawing library, no runtime dependency of its own) included —
 *   and write it with its provenance and licences in the header. The parser's
 *   command-line tail (`require('fs')`, `require.main`) is cut: it has no
 *   meaning in a browser.
 *
 *   node scripts/vendor-ebnf2railroad.mjs            # regenerate
 *   node scripts/vendor-ebnf2railroad.mjs --check    # exit 1 if out of date
 *
 *   To upgrade: change VERSION, regenerate, run the tests, commit the result.
 *
 ******************************************************************************/

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const VERSION = '1.14.3';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = join(ROOT, 'packages/markpage-render/src/vendor/ebnf2railroad.ts');

const work = mkdtempSync(join(tmpdir(), 'vendor-ebnf-'));
try {
  writeFileSync(join(work, 'package.json'), '{"private":true}\n');
  execFileSync(
    'npm',
    ['install', '--ignore-scripts', '--no-audit', '--no-fund', '--no-package-lock', `ebnf2railroad@${VERSION}`],
    { cwd: work, stdio: ['ignore', 'ignore', 'inherit'] },
  );
  const pkg = (name) => JSON.parse(readFileSync(join(work, 'node_modules', name, 'package.json'), 'utf8'));
  const ebnf = pkg('ebnf2railroad');
  const rr = pkg('@prantlf/railroad-diagrams');
  const licence = readFileSync(join(work, 'node_modules/ebnf2railroad/LICENSE'), 'utf8').trim();

  writeFileSync(
    join(work, 'entry.js'),
    [
      "export { parse } from 'ebnf2railroad/src/ebnf-parser';",
      "export { createDiagram } from 'ebnf2railroad/src/build-diagram';",
      "export { createStructuralToc, createDefinitionMetadata } from 'ebnf2railroad/src/toc';",
      '',
    ].join('\n'),
  );

  // The jison-generated parser ends with a command-line entry point.
  const CLI_TAIL = /exports\.main = function commonjsMain[\s\S]*?\n\}\s*$/;
  // … and guards its exports on `require` existing, which would make esbuild
  // ship a `require` shim for a test that is always true here.
  const CJS_GUARD = "if (typeof require !== 'undefined' && typeof exports !== 'undefined')";
  const result = await build({
    absWorkingDir: work,
    entryPoints: ['entry.js'],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    write: false,
    legalComments: 'none',
    logLevel: 'warning',
    plugins: [
      {
        name: 'cut-parser-cli',
        setup(b) {
          b.onLoad({ filter: /ebnf2railroad[\\/]src[\\/]ebnf-parser\.js$/ }, (args) => {
            const src = readFileSync(args.path, 'utf8');
            if (!CLI_TAIL.test(src)) throw new Error('ebnf-parser.js: command-line tail not found');
            if (!src.includes(CJS_GUARD)) throw new Error('ebnf-parser.js: CommonJS guard not found');
            return {
              contents: src.replace(CLI_TAIL, '}\n').replace(CJS_GUARD, "if (typeof exports !== 'undefined')"),
              loader: 'js',
            };
          });
        },
      },
    ],
  });
  const code = result.outputFiles[0].text;
  // esbuild's own `function __require()` wrapper is fine; its `var __require`
  // shim, or a bare call, would mean something Node-only got in.
  const stray = code.split('\n').filter((l) => /\bvar __require\b|(?<!function )(?<![\w$])(?:__)?require\(/.test(l));
  if (stray.length > 0) throw new Error(`the bundle still calls require():\n${stray.join('\n')}`);

  const header = `// @ts-nocheck
/* eslint-disable */
/*************************** vendor/ebnf2railroad.ts ***************************
 *
 * GENERATED by scripts/vendor-ebnf2railroad.mjs — do not edit by hand.
 *
 * The part of ebnf2railroad the \`ebnf\` fence uses (parser, diagram builder,
 * table-of-contents helpers), bundled into one ES module:
 *
 *   ebnf2railroad ${ebnf.version} — ${ebnf.license}
 *     https://github.com/matthijsgroen/ebnf2railroad
 *   @prantlf/railroad-diagrams ${rr.version} — ${rr.license}
 *     ${rr.homepage}
 *
 * Why a copy and not a dependency: see the script.
 *
 * ---------------------------------------------------------------------------
 * ebnf2railroad:
 *
${licence.split('\n').map((l) => (l ? ` * ${l}` : ' *')).join('\n')}
 *
 ******************************************************************************/

`;
  const out = header + code;

  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(TARGET, 'utf8');
    } catch {
      /* missing: out of date */
    }
    if (current !== out) {
      console.error(`${TARGET} is out of date: run node scripts/vendor-ebnf2railroad.mjs`);
      process.exitCode = 1;
    } else {
      console.log('vendor/ebnf2railroad.ts is up to date');
    }
  } else {
    writeFileSync(TARGET, out);
    console.log(`wrote ${TARGET} (${(out.length / 1024).toFixed(0)} kB, ebnf2railroad ${ebnf.version})`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
